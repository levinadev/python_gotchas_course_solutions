"""
Урок 5.4 "Что скрывают фигурные скобки", шаг 5

Считайте две строки со словами. Выведите слова, которые есть в обеих строках, в алфавитном порядке.
Если таких слов нет, выведите `нет общих`.
"""

first = set(input().split())
second = set(input().split())
common = sorted(first & second)
print(*common if common else ["нет общих"])
