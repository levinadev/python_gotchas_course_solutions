"""
Урок 5.3 "Словарь, который теряет ключи", шаг 7

Считайте поездки, по одной на строке, это город отправления и город прибытия. Посчитайте, сколько
раз встречается каждый маршрут. Ключом словаря список быть не может, поэтому храните маршрут
кортежем.

Ввод. Несколько строк, в каждой два города через пробел.

Вывод. Для каждого маршрута в порядке первого появления строка `откуда куда количество`.
"""

import sys

routes = {}
for line in sys.stdin.read().splitlines():
    route = tuple(line.split())
    routes[route] = routes.get(route, 0) + 1
for (start, finish), n in routes.items():
    print(start, finish, n)
