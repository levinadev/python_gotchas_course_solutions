"""
Урок 5.1 "Кортеж не то, чем кажется", шаг 6

Считайте целые числа. Составьте из чётных чисел кортеж и выведите его целиком, `print(t)`, в том
виде, в каком его показывает Python.

Ввод. Целые числа через пробел.

Вывод. Кортеж из чётных чисел в порядке ввода.
"""

nums = list(map(int, input().split()))
t = tuple(x for x in nums if x % 2 == 0)
print(t)
