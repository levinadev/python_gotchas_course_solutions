"""
Урок 9.1 "Всё вместе", шаг 8

Считайте таблицу чисел. Создайте её копию, в которой все отрицательные числа заменены нулями.
Исходная таблица должна остаться без изменений.

Ввод. Несколько строк с целыми числами через пробел (во всех строках одинаковое количество чисел).

Вывод. Сначала строки копии, затем строка `---`, затем строки исходной таблицы.
"""

import sys

table = [list(map(int, line.split())) for line in sys.stdin.read().splitlines()]
clean = [[max(x, 0) for x in row] for row in table]
for row in clean:
    print(*row)
print("---")
for row in table:
    print(*row)
