"""
Урок 3.3 "Таблица, которая меняется целым столбцом", шаг 7

Считайте число `n` и список неотрицательных целых чисел. Разложите числа по `n` корзинам. Число
попадает в корзину, номер которой равен остатку от деления этого числа на `n`.

Ввод. Число `n` (от 1 до 9), затем строка с числами через пробел.

Вывод. `n` строк вида `номер: числа` в порядке номеров корзин. Числа идут в порядке ввода, пустая
корзина выводится как `номер: пусто`.
"""

n = int(input())
nums = list(map(int, input().split()))
baskets = [[] for _ in range(n)]
for x in nums:
    baskets[x % n].append(x)
for i, basket in enumerate(baskets):
    print(f"{i}:", *basket if basket else ["пусто"])
