"""
Урок 3.1 "Один список изменился, и второй тоже", шаг 5

Считайте маршрут, это названия городов через пробел. Создайте копию маршрута `short` и удалите из
неё все города, в названии которых меньше 5 букв. Исходный маршрут `route` должен остаться без
изменений.

Вывод. Две строки, исходный маршрут и сокращённый. Если в сокращённом не осталось городов, выведите
во второй строке `пусто`.
"""

route = input().split()
short = [city for city in route if len(city) >= 5]
print(*route)
print(*short if short else ["пусто"])
