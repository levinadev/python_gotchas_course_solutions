"""
Урок 3.1 "Один список изменился, и второй тоже", шаг 6

Считайте шаблон меню, номер блюда `k` (нумерация с единицы) и новое блюдо. Создайте копию меню на
сегодня и замените в ней блюдо номер `k` на новое. Шаблон должен остаться без изменений.

Ввод. Три строки, блюда шаблона через пробел, номер `k` и новое блюдо.

Вывод. Две строки, шаблон и меню на сегодня.
"""

template = input().split()
k = int(input())
dish = input()
menu = template.copy()
menu[k - 1] = dish
print(*template)
print(*menu)
