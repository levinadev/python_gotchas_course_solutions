"""
Урок 3.4 "Цикл, который пропускает элементы", шаг 3

Программа должна удалить из списка температур все отрицательные значения. На некоторых данных
отрицательные числа остаются.

Найдите и исправьте ошибку.

Ввод. Целые числа через пробел.

Вывод. Оставшиеся числа через пробел. Если ничего не осталось, выведите `нет данных`.

Программа с ошибкой, которая лежит в редакторе на Stepik

    temps = list(map(int, input().split()))
    for t in temps:
        if t < 0:
            temps.remove(t)
    print(*temps if temps else ["нет данных"])
"""

temps = list(map(int, input().split()))
temps = [t for t in temps if t >= 0]
print(*temps if temps else ["нет данных"])
