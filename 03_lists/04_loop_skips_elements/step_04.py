"""
Урок 3.4 "Цикл, который пропускает элементы", шаг 4

Считайте список слов и букву. Удалите из списка все слова, которые начинаются с этой буквы (без
учёта регистра).

Ввод. Строка со словами через пробел, затем строка с одной буквой.

Вывод. Оставшиеся слова через пробел или `пусто`, если не осталось ни одного.
"""

words = input().split()
letter = input().lower()
words = [w for w in words if not w.lower().startswith(letter)]
print(*words if words else ["пусто"])
