"""
Урок 6.1 "Простая сумма с неверным ответом", шаг 6

Посчитайте сдачу. Чтобы не получить погрешность дробных чисел, считайте через `Decimal`.

Ввод. Строка с ценами через пробел, затем строка с суммой, которую дал покупатель. У всех чисел не
больше двух знаков после точки, сумма покупателя не меньше суммы цен.

Вывод. Сдача ровно с двумя знаками после точки.
"""

from decimal import Decimal

prices = [Decimal(x) for x in input().split()]
paid = Decimal(input())
print((paid - sum(prices)).quantize(Decimal("0.01")))
