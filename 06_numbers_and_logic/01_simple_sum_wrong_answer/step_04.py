"""
Урок 6.1 "Простая сумма с неверным ответом", шаг 4

Программа проверяет, что сумма цен в чеке совпадает с итогом. На некоторых чеках она пишет `Не
сходится`, хотя всё верно.

Найдите и исправьте ошибку.

Ввод. Строка с ценами через пробел (дробные числа), затем строка с итогом.

Вывод. `Сходится` или `Не сходится`.

Программа с ошибкой, которая лежит в редакторе на Stepik

    prices = list(map(float, input().split()))
    total = float(input())
    if sum(prices) == total:
        print("Сходится")
    else:
        print("Не сходится")
"""

import math

prices = list(map(float, input().split()))
total = float(input())
if math.isclose(sum(prices), total):
    print("Сходится")
else:
    print("Не сходится")
