"""
Урок 6.1 "Простая сумма с неверным ответом", шаг 5

Программа проверяет, хватит ли денег на покупки. Иногда она пишет `Не хватает`, хотя денег ровно
столько, сколько нужно.

Найдите и исправьте ошибку.

Ввод. Строка с ценами через пробел, затем строка с имеющейся суммой. У всех чисел не больше двух
знаков после точки.

Вывод. `Хватает` или `Не хватает`.

Программа с ошибкой, которая лежит в редакторе на Stepik

    prices = list(map(float, input().split()))
    budget = float(input())
    if sum(prices) <= budget:
        print("Хватает")
    else:
        print("Не хватает")
"""

prices = list(map(float, input().split()))
budget = float(input())
if round(sum(prices), 2) <= budget:
    print("Хватает")
else:
    print("Не хватает")
