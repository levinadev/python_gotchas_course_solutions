"""
Урок 6.3 "Минус в делении меняет ответ", шаг 6

Дни недели пронумерованы от 1 (понедельник) до 7 (воскресенье). Сегодня день с номером `d`. Какой
день недели будет через `k` дней? Отрицательное `k` означает, что нужно узнать, какой день был
столько дней назад.

Ввод. Две строки, числа `d` и `k` (`k` от -1000 до 1000).

Вывод. Название дня строчными буквами.
"""

days = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"]
d = int(input())
k = int(input())
print(days[(d - 1 + k) % 7])
