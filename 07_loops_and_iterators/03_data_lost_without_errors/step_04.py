"""
Урок 7.3 "Данные пропали без единой ошибки", шаг 4

Программа печатает ведомость с именами и баллами участников. Если количество имён и баллов не
совпадает, она должна вывести `Ошибка в данных`, но вместо этого молча теряет часть участников.

Исправьте программу.

Ввод. Строка с именами через пробел, строка с баллами через пробел.

Вывод. Строки `имя: балл` или одна строка `Ошибка в данных`.

Программа с ошибкой, которая лежит в редакторе на Stepik

    names = input().split()
    scores = input().split()
    for name, score in zip(names, scores):
        print(f"{name}: {score}")
"""

names = input().split()
scores = input().split()
if len(names) != len(scores):
    print("Ошибка в данных")
else:
    for name, score in zip(names, scores):
        print(f"{name}: {score}")
