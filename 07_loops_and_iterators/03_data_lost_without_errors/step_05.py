"""
Урок 7.3 "Данные пропали без единой ошибки", шаг 5

Выведите все числа от `a` до `b` включительно с шагом `step`. Числа `a` и `b` могут идти в любом
порядке. Если `a > b`, числа выводятся по убыванию.

Ввод. Три целых числа `a`, `b` и `step` (`step > 0`) через пробел.

Вывод. Числа через пробел.
"""

a, b, step = map(int, input().split())
if a <= b:
    print(*range(a, b + 1, step))
else:
    print(*range(a, b - 1, -step))
