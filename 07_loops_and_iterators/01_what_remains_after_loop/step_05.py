"""
Урок 7.1 "Что остаётся после цикла", шаг 5

Найдите первое отрицательное число в списке. Используйте цикл `for` с веткой `else`.

Ввод. Целые числа через пробел.

Вывод. Позиция первого отрицательного числа (нумерация с нуля) и само число через пробел. Если
отрицательных нет, выведите `нет`.
"""

nums = list(map(int, input().split()))
for i, x in enumerate(nums):
    if x < 0:
        print(i, x)
        break
else:
    print("нет")
