"""
Урок 7.1 "Что остаётся после цикла", шаг 7

Выведите первое слово строки, в котором больше `k` букв. Если таких слов нет, выведите последнее
слово строки.

Решите задачу одним циклом `for` и воспользуйтесь тем, что переменная цикла сохраняет значение после
цикла.

Ввод. Строка со словами через пробел, затем строка с числом `k`.
"""

words = input().split()
k = int(input())
for word in words:
    if len(word) > k:
        break
print(word)
