"""
Урок 2.2 "Один оператор, два разных результата", шаг 8

Строку нельзя изменить по индексу, `word[i] = ch` вызовет ошибку `TypeError`. Соберите новую строку,
в которой символ с индексом `i` заменён на `ch`.

Ввод. Три строки, это слово, индекс `i` (от 0 до длины слова минус 1) и один символ `ch`.

Вывод. Новое слово.
"""

word = input()
i = int(input())
ch = input()
print(word[:i] + ch + word[i + 1:])
