"""
Урок 2.3 "Равны, но не одинаковы", шаг 7

Считайте два списка чисел `a` и `b`. Затем создайте имя `c`, которое указывает на тот же список, что
и `a`.

Выведите три строки с результатами `a == b`, `a is b` и `a is c`.

Ввод. Две строки с целыми числами через пробел.
"""

a = list(map(int, input().split()))
b = list(map(int, input().split()))
c = a
print(a == b)
print(a is b)
