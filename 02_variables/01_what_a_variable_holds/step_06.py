"""
Урок 2.1 "Что на самом деле хранит переменная", шаг 6

Программа считывает список чисел. Имя `original` указывает на тот же список, что и `nums`. Умножьте
каждый элемент на 2 так, чтобы изменения увидело имя `original`.

Создавать новый список нельзя. Если написать `nums = ...`, наклейка `nums` переедет на новый список,
а `original` останется на старом.

Ввод. Целые числа через пробел.

Вывод. Элементы `original` через пробел.

Программа с ошибкой, которая лежит в редакторе на Stepik

    nums = list(map(int, input().split()))
    original = nums

    # измените список nums на месте

    print(*original)
"""

nums = list(map(int, input().split()))
original = nums

for i in range(len(nums)):
    nums[i] *= 2

print(*original)
